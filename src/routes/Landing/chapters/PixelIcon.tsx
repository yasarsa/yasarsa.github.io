import type { AchievementIcon } from '../../../data/gameMeta';

/** 8×8 bitmaps — '#' is a lit pixel. */
const BITMAPS: Record<AchievementIcon, string[]> = {
    star: ['...##...', '...##...', '########', '.######.', '..####..', '.##..##.', '##....##', '........'],
    trophy: ['########', '#.####.#', '#.####.#', '.######.', '..####..', '...##...', '..####..', '.######.'],
    scroll: ['.######.', '#......#', '.#.##.#.', '.#....#.', '.#.##.#.', '.#....#.', '.######.', '#......#'],
    plane: ['...##...', '...##...', '.######.', '########', '...##...', '...##...', '..####..', '.##..##.'],
    heart: ['.##..##.', '########', '########', '########', '.######.', '..####..', '...##...', '........'],
    crown: ['#..##..#', '#..##..#', '##.##.##', '########', '########', '.######.', '.######.', '........'],
    shield: ['########', '#.####.#', '########', '########', '.######.', '.######.', '..####..', '...##...'],
    mic: ['..####..', '..####..', '..####..', '..####..', '#.####.#', '.#....#.', '..####..', '...##...'],
    chat: ['########', '#......#', '#.#.#.##', '#......#', '########', '..##....', '.#......', '........'],
};

export default function PixelIcon({ icon, className }: { icon: AchievementIcon; className?: string }) {
    const rows = BITMAPS[icon];
    return (
        <svg className={className} viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden="true">
            {rows.flatMap((row, y) =>
                [...row].map((px, x) => (px === '#' ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" /> : null))
            )}
        </svg>
    );
}
